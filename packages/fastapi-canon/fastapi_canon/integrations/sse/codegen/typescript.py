import json
import re
from importlib.resources import files

from fastapi_canon.integrations.sse.codegen.documentation import operation_doc
from fastapi_canon.integrations.sse.codegen.ir import (
    Array,
    Contract,
    EnumAlias,
    EnumValue,
    Intersection,
    LiteralType,
    Object,
    Operation,
    Reference,
    Scalar,
    StringEnum,
    Type,
    Union,
)
from fastapi_canon.integrations.sse.codegen.names import identifier
from fastapi_canon.integrations.sse.codegen.openapi import ContractError
from fastapi_canon.integrations.sse.codegen.templating import add_filters, environment

_HEADER = "// Generated by fastapi-canon. Do not edit.\n"
_JSON = (
    "export type JsonValue = string | number | boolean | null "
    "| JsonValue[] | { [key: string]: JsonValue };"
)


def render_type(type_: Type, prefix: str = "") -> str:
    match type_:
        case Scalar(name="JsonValue"):
            return prefix + "JsonValue"
        case Scalar(name="integer"):
            return "number"
        case Scalar(name=name):
            return name
        case LiteralType(value=value):
            return json.dumps(value, ensure_ascii=False)
        case EnumValue(enum=enum, member=member):
            return f"typeof {prefix}{enum}.{member}"
        case StringEnum(members=members):
            return " | ".join(json.dumps(member.value) for member in members)
        case EnumAlias(target=target):
            return prefix + target
        case Reference(name=name):
            return prefix + name
        case Array(item=item):
            return f"Array<{render_type(item, prefix=prefix)}>"
        case Union(members=members):
            return " | ".join(
                dict.fromkeys(render_type(part, prefix=prefix) for part in members)
            )
        case Intersection(members=members):
            return " & ".join(
                f"({render_type(part, prefix=prefix)})"
                if isinstance(part, Union)
                else render_type(part, prefix=prefix)
                for part in members
            )
        case Object(fields=fields, additional=additional):
            parts = [
                f"{_property_name(field.name)}{'' if field.required else '?'}: "
                f"{render_type(field.type, prefix=prefix)};"
                for field in fields
            ]
            if additional is not None:
                values = {render_type(additional, prefix=prefix)}
                values.update(
                    render_type(field.type, prefix=prefix) for field in fields
                )
                if any(not field.required for field in fields):
                    values.add("undefined")
                parts.append(f"[key: string]: {' | '.join(sorted(values))};")
            # An empty model is a JSON object, not TypeScript's non-nullish {} type.
            return (
                "{\n" + "\n".join("  " + part for part in parts) + "\n}"
                if parts
                else "{ [key: string]: never }"
            )


def generate_typescript(contract: Contract) -> dict[str, str]:
    public_names = {
        "Client",
        "ClientOptions",
        "RequestOptions",
        "HttpError",
        "isHttpError",
        "StreamParseError",
        "TransportError",
    }
    for declaration in contract.declarations:
        if declaration.name in public_names:
            raise ContractError(f"Reserved TypeScript model name: {declaration.name}")
        public_names.add(declaration.name)
    for operation in contract.operations:
        names = (
            [_input_name(operation)] if operation.parameters or operation.body else []
        )
        if operation.errors:
            names.extend(
                identifier(operation.operation_id, upper=True) + suffix
                for suffix in ("Error", "ErrorBody")
            )
        for name in names:
            if name in public_names:
                raise ContractError(f"TypeScript public name collision: {name}")
            public_names.add(name)
    env = environment()

    def pascal(value: str) -> str:
        return identifier(value, upper=True)

    def documentation(operation: Operation) -> str:
        return operation_doc(operation, "typescript")

    def event_policy(operation: Operation) -> str | None:
        return _event_policy(contract, operation)

    add_filters(
        env,
        ts_type=render_type,
        json=json.dumps,
        pascal=pascal,
        input_name=_input_name,
        required=_required,
        error_type=_error_type,
        path=_path,
        operation_doc=documentation,
        event_policy=event_policy,
    )
    output: dict[str, str] = {}
    declarations: list[str] = []
    for declaration in contract.declarations:
        name, type_ = declaration.name, declaration.type
        if isinstance(type_, StringEnum):
            members = "\n".join(
                f"  {member.name}: {json.dumps(member.value)},"
                for member in type_.members
            )
            declarations.append(
                f"export const {name} = {{\n{members}\n}} as const;\n"
                f"export type {name} = (typeof {name})[keyof typeof {name}];"
            )
        elif isinstance(type_, EnumAlias):
            declarations.append(
                f"export const {name} = {type_.target};\n"
                f"export type {name} = {type_.target};"
            )
        else:
            declarations.append(f"export type {name} = {render_type(type_)};")
    output["types.ts"] = "\n".join([_HEADER, _JSON, "", *declarations]) + "\n"
    for template in ("sse.ts", "errors.ts"):
        output[f"transport/{template}"] = (
            files(__package__)
            .joinpath(f"templates/{template}")
            .read_text(encoding="utf-8")
        )
    grouped: dict[str, list[Operation]] = {}
    for operation in contract.operations:
        grouped.setdefault(operation.group, []).append(operation)
    groups: list[dict[str, str]] = []
    exports = [
        _HEADER,
        'export { createClient } from "./client.js";',
        'export type { Client } from "./client.js";',
        'export * from "./types.js";',
        'export type { ClientOptions, RequestOptions } from "./transport/sse.js";',
        "export { HttpError, isHttpError, TransportError, StreamParseError } "
        'from "./transport/errors.js";',
    ]
    for group, operations in sorted(grouped.items()):
        operations.sort(key=lambda operation: operation.name)
        directory = operations[0].directory
        factory = "create" + group[:1].upper() + group[1:] + "Api"
        groups.append(dict(name=group, factory=factory, directory=directory))
        functions = ["stream"]
        if any(
            param.location == "path" for op in operations for param in op.parameters
        ):
            functions.append("encodePath")
        if any(
            param.location == "query" for op in operations for param in op.parameters
        ):
            functions.append("appendQuery")
        if any(
            param.location == "header" for op in operations for param in op.parameters
        ):
            functions.append("setHeader")
        output[f"{directory}/api.ts"] = env.get_template("typescript/api.ts.j2").render(
            operations=operations,
            functions=functions,
            factory=factory,
        )
        output[f"{directory}/index.ts"] = _HEADER + 'export * from "./api.js";\n'
        exports.append(f'export type * from "./{directory}/api.js";')
    output["client.ts"] = env.get_template("typescript/client.ts.j2").render(
        groups=groups
    )
    output["index.ts"] = "\n".join(exports) + "\n"
    return output


def _event_policy(contract: Contract, operation: Operation) -> str | None:
    """Discriminator and known tags for the `unknownEvents: "ignore"` option."""
    types = {item.name: item.type for item in contract.declarations}

    def resolve(type_: Type) -> Type:
        seen: set[str] = set()
        while isinstance(type_, Reference) and type_.name not in seen:
            seen.add(type_.name)
            type_ = types.get(type_.name, type_)
        return type_

    def tags(type_: Type) -> list[str] | None:
        match resolve(type_):
            case LiteralType(value=str(value)):
                return [value]
            case EnumValue(enum=enum, member=member):
                enum_type = resolve(Reference(enum))
                if not isinstance(enum_type, StringEnum):
                    return None
                return [item.value for item in enum_type.members if item.name == member]
            case StringEnum(members=members):
                return [item.value for item in members]
            case EnumAlias(target=target):
                return tags(Reference(target))
            case Union(members=members):
                parts = [tags(item) for item in members]
                if any(part is None for part in parts):
                    return None
                return [value for part in parts if part for value in part]
            case _:
                return None

    union = resolve(operation.event)
    if not isinstance(union, Union) or union.discriminator is None:
        return None
    known: list[str] = []
    for member in union.members:
        variant = resolve(member)
        if not isinstance(variant, Object):
            return None
        field = next(
            (item for item in variant.fields if item.name == union.discriminator), None
        )
        values = None if field is None else tags(field.type)
        if not values:
            return None
        known.extend(values)
    policy = {"discriminator": union.discriminator, "known": sorted(set(known))}
    return json.dumps(policy, ensure_ascii=False)


def _input_name(operation: Operation) -> str:
    return identifier(operation.operation_id, upper=True) + "Params"


def _property_name(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else json.dumps(name)


def _path(operation: Operation) -> str:
    parts: list[str] = []
    cursor = 0
    by_name = {param.name: param.argument for param in operation.parameters}
    for match in re.finditer(r"\{([^{}]+)\}", operation.path):
        parts.append(json.dumps(operation.path[cursor : match.start()]))
        parts.append(f"encodePath(input.{by_name[match[1]]})")
        cursor = match.end()
    parts.append(json.dumps(operation.path[cursor:]))
    return " + ".join(parts)


def _required(operation: Operation) -> bool:
    return any(param.required for param in operation.parameters) or (
        operation.body is not None and operation.body.required
    )


def _error_type(operation: Operation) -> str:
    return " | ".join(
        sorted({render_type(error.type, prefix="Types.") for error in operation.errors})
    )
