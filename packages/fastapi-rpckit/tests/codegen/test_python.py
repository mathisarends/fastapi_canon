def test_long_event_models_and_route_annotations_are_ruff_clean(
    document: dict[str, Any],
    options: PythonClientOptions,
    tmp_path: Path,
) -> None:
    deployed = deepcopy(document)
    schemas = deployed["components"]["schemas"]
    event_names = [
        "VoiceAssistantAudioCompleted",
        "VoiceAssistantAudioStarted",
        "VoiceAssistantToolCompleted",
        "VoiceAssistantToolStarted",
    ]
    for name in event_names:
        schemas[name] = {
            "type": "object",
            "properties": {
                "type": {"type": "string", "const": name, "default": name},
            },
            "required": ["type"],
        }
    schemas["VoiceAssistantEvent"] = {
        "oneOf": [{"$ref": f"#/components/schemas/{name}"} for name in event_names],
        "discriminator": {
            "propertyName": "type",
            "mapping": {name: f"#/components/schemas/{name}" for name in event_names},
        },
    }
    schemas["ExtraordinarilyLongMediaPlaybackRequestParams"] = {
        "type": "object",
        "properties": {"uri": {"type": "string"}},
        "required": ["uri"],
    }
    method = deepcopy(deployed["methods"][0])
    method["name"] = "voice.assistant_audio_playback_completed"
    method["params"] = [
        {
            "name": "params",
            "required": True,
            "schema": {
                "$ref": "#/components/schemas/"
                "ExtraordinarilyLongMediaPlaybackRequestParams"
            },
        }
    ]
    method["result"] = {
        "name": "result",
        "schema": {"$ref": "#/components/schemas/VoiceAssistantEvent"},
    }
    deployed["methods"].append(method)

    schemas["PlaybackCommandParams"] = schemas[
        "ExtraordinarilyLongMediaPlaybackRequestParams"
    ]
    shorter = deepcopy(method)
    shorter["name"] = "voice.turn.start"
    shorter["params"][0]["schema"]["$ref"] = (
        "#/components/schemas/PlaybackCommandParams"
    )
    deployed["methods"].append(shorter)

    _assert_ruff_clean(deployed, options, tmp_path)


def _methods_only() -> RpcChannel:
    channel = RpcChannel("demo")

    @channel.method
    async def echo(params: _Params) -> _Result: ...

    return channel


def _events_only() -> RpcChannel:
    channel = RpcChannel("demo")

    @channel.event
    async def ticks() -> AsyncIterator[_Tick]:
        yield _Tick(n=1)

    return channel


def _methods_and_events() -> RpcChannel:
    channel = RpcChannel("demo", raises=(_MissingError,))

    @channel.method
    async def echo(params: _Params) -> _Result: ...

    @channel.event
    async def ticks() -> AsyncIterator[_Tick]:
        yield _Tick(n=1)

    return channel


def _all_stream_directions() -> RpcChannel:
    channel = RpcChannel("media")

    @channel.method
    async def echo(params: _Params) -> _Result: ...

    @channel.stream
    async def preview() -> AsyncIterator[bytes]:
        yield b""

    @channel.stream(input_content_type="audio/pcm")
    async def upload(session_id: str, frames: Inject[RpcBinaryInput]) -> None:
        pass

    @channel.stream(content_type="audio/opus")
    async def talk(
        session_id: str,
        frames: Inject[RpcBinaryInput],
        output: Inject[RpcBinaryOutput],
    ) -> None:
        pass

    return channel


@pytest.mark.parametrize(
    "channel",
    [_methods_only, _events_only, _methods_and_events, _all_stream_directions],
)
@pytest.mark.parametrize("transport", [None, "websocket"])
def test_generated_python_from_services_is_ruff_clean(
    channel: Callable[[], RpcChannel],
    transport: str | None,
    tmp_path: Path,
) -> None:
    service = RpcService()
    mounted = channel()
    service.socket("/v1/gateway", channels=[mounted])
    for stream in mounted.streams:
        local = stream.name.rsplit(".", 1)[-1]
        prefix = "/v1/{session_id}" if stream.path_parameters else "/v1"
        service.stream(f"{prefix}/{local}", stream.function)
    contract = service.contract(title="Gateway", base_url="http://localhost")

    _assert_ruff_clean(
        contract.to_openrpc(),
        PythonClientOptions(package=PACKAGE, with_transport=transport),
        tmp_path,
    )


def _assert_ruff_clean(
    document: dict[str, Any],
    options: PythonClientOptions,
    tmp_path: Path,
) -> None:
    output = tmp_path / PACKAGE
    generate_python_client(document, output, options)
    (tmp_path / "pyproject.toml").write_text(
        '[tool.ruff]\nline-length = 88\n[tool.ruff.lint]\nselect = ["E", "F", "I"]\n'
        f'[tool.ruff.lint.isort]\nknown-first-party = ["{PACKAGE}"]\n',
        encoding="utf-8",
    )

    lint = subprocess.run(
        [sys.executable, "-m", "ruff", "check", str(output)],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=False,
    )
    formatting = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--check", str(output)],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=False,
    )

    assert lint.returncode == 0, lint.stdout + lint.stderr
    assert formatting.returncode == 0, formatting.stdout + formatting.stderr
