def test_writing_is_idempotent_and_check_does_not_write(
    document: dict[str, Any],
    tmp_path: Path,
) -> None:
    output = tmp_path / "generated"

    assert len(generate_typescript_client(document, output, options())) == 9
    assert generate_typescript_client(document, output, options()) == ()
    (output / "client.ts").write_text("stale\n", encoding="utf-8")

    assert generate_typescript_client(document, output, options(), check=True) == (
        output / "client.ts",
    )
    assert (output / "client.ts").read_text(encoding="utf-8") == "stale\n"


def test_generated_typescript_is_prettier_formatted(
    document: dict[str, Any],
    tmp_path: Path,
) -> None:
    output = tmp_path / "generated"
    nested = deepcopy(document)
    first = nested["methods"][0]
    second = deepcopy(first)
    first["name"] = "tasks.list"
    second["name"] = "tasks.status.set"
    nested["methods"] = [first, second]
    nested["x-rpckit-binary-streams"] = [
        {
            "name": "voice",
            "url": "wss://media",
            "direction": "server-to-client",
            "frameType": "binary",
        },
        {
            "name": "uploads.audio",
            "url": "wss://media/{sessionId}/upload",
            "direction": "client-to-server",
            "inputContentType": "audio/pcm",
            "frameType": "binary",
            "variables": {"sessionId": {"default": "demo"}},
        },
        {
            "name": "uploads.talk",
            "url": "wss://media/talk",
            "direction": "bidirectional",
            "contentType": "audio/opus",
            "inputContentType": "audio/pcm",
            "frameType": "binary",
        },
    ]
    generate_typescript_client(nested, output, options())
    nested["servers"] = [
        {
            "name": "control",
            "url": "wss://api/rpc",
            "x-rpckit-transport": {
                "type": "websocket",
                "messageEncoding": "json",
            },
        }
    ]
    configured = TypeScriptClientOptions(
        client_name="GreetingClient",
        source="greeting.openrpc.json",
        with_transport="websocket",
    )
    websocket_media = render_typescript_client(nested, configured)["streams.ts"]
    with (output / "media-websocket.ts").open(
        "w", encoding="utf-8", newline="\n"
    ) as handle:
        handle.write(websocket_media)
    prettier = shutil.which("npx.cmd") or shutil.which("npx")
    if prettier is None:
        pytest.skip("npx is not installed")

    formatting = subprocess.run(
        [prettier, "prettier", "--check", str(output)],
        capture_output=True,
        text=True,
        check=False,
    )

    assert formatting.returncode == 0, formatting.stdout + formatting.stderr


def test_generated_typescript_passes_strict_type_checking(
    document: dict[str, Any],
    tmp_path: Path,
) -> None:
    npx = shutil.which("npx.cmd") or shutil.which("npx")
    if npx is None:
        pytest.skip("npx is not installed")

    output = tmp_path / "generated"
    deployed = deepcopy(document)
    deployed["servers"] = [
        {
            "name": "primary",
            "url": "wss://{host}/rpc",
            "variables": {"host": {"default": "api.example.com"}},
            "x-rpckit-transport": {
                "type": "websocket",
                "messageEncoding": "json",
            },
        }
    ]
    deployed["x-rpckit-binary-streams"] = [
        {
            "name": "greeting.frames",
            "url": "wss://{host}/frames",
            "direction": "server-to-client",
            "contentType": "image/jpeg",
            "frameType": "binary",
            "variables": {"host": {"default": "api.example.com"}},
        }
    ]
    generate_typescript_client(
        deployed,
        output,
        TypeScriptClientOptions(
            client_name="GreetingClient",
            source="greeting.openrpc.json",
            with_transport="websocket",
        ),
    )
    consumer = tmp_path / "consumer.ts"
    consumer.write_text(
        dedent(
            """
            import {
              notifications,
              routes,
              type GreetedResult,
              type GreetingUpdate,
              type RpcClientCore,
              type SayResult,
            } from "./generated";

            declare const rpc: RpcClientCore;

            const result: Promise<SayResult> = rpc.request(
              routes.greetingSay,
              { name: "Ada" },
            );
            const greeted: Promise<GreetedResult> = rpc.request(
              routes.greetingGreeted,
            );
            const updates: AsyncIterable<GreetingUpdate> = rpc.notifications(
              notifications.greetingChanged,
            );

            // @ts-expect-error greeting.say requires parameters
            void rpc.request(routes.greetingSay);
            // @ts-expect-error greeting.greeted does not accept parameters
            void rpc.request(routes.greetingGreeted, {});
            // @ts-expect-error name is a string
            void rpc.request(routes.greetingSay, { name: 42 });

            void result;
            void greeted;
            void updates;
            """
        ),
        encoding="utf-8",
        newline="\n",
    )

    type_check = subprocess.run(
        [
            npx,
            "--yes",
            "--package",
            "typescript",
            "tsc",
            "--noEmit",
            "--strict",
            "--target",
            "ES2022",
            "--module",
            "ESNext",
            "--moduleResolution",
            "Bundler",
            "--lib",
            "ES2022,DOM,ESNext.Disposable",
            "--skipLibCheck",
            str(consumer),
        ],
        capture_output=True,
        text=True,
        check=False,
    )

    assert type_check.returncode == 0, type_check.stdout + type_check.stderr


def test_contracts_without_models_do_not_export_a_models_module() -> None:
    channel = RpcChannel("control")

    @channel.method
    async def ping() -> str:
        return "pong"

    service = RpcService()
    service.socket("/rpc", channels=[channel])
    document = service.contract(title="Control", base_url="ws://localhost")

    files = render_typescript_client(document.to_openrpc(), options())

    assert "models.ts" not in files
    assert "./models" not in files["index.ts"]


def test_sdk_error_types_do_not_require_upgrading_the_consumers_lib_target(
    document: dict[str, Any], tmp_path: Path
) -> None:
    npx = shutil.which("npx.cmd") or shutil.which("npx")
    if npx is None:
        pytest.skip("npx is required")
    deployed = deepcopy(document)
    deployed["servers"] = [
        {
            "name": "rpc",
            "url": "ws://test",
            "x-rpckit-transport": {"type": "websocket", "messageEncoding": "json"},
        }
    ]
    generate_typescript_client(
        deployed,
        tmp_path / "generated",
        TypeScriptClientOptions(with_transport="websocket"),
    )
    consumer = tmp_path / "consumer.ts"
    consumer.write_text(
        dedent("""
        import {
          RpcClientError, RpcConnectionLostError, RpcConnectError,
        } from "./generated";
        const cause = new Error("reset");
        const error: RpcClientError = new RpcConnectionLostError(
          true, 1011, "closed", { cause },
        );
        const connect = RpcConnectError.fromCause(cause);
        void error.cause;
        void connect.permanent;
        """),
        encoding="utf-8",
    )
    result = subprocess.run(
        [
            npx,
            "--yes",
            "--package",
            "typescript",
            "tsc",
            "--noEmit",
            "--strict",
            "--target",
            "ES2021",
            "--module",
            "ESNext",
            "--moduleResolution",
            "Bundler",
            "--lib",
            "ES2021,DOM,ESNext.Disposable",
            "--skipLibCheck",
            str(consumer),
        ],
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stdout + result.stderr
