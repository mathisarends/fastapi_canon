def options() -> TypeScriptClientOptions:
    return TypeScriptClientOptions(
        client_name="GreetingClient",
        source="greeting.openrpc.json",
    )


def test_the_generated_package_has_one_module_per_concern(
    document: dict[str, Any],
) -> None:
    files = render_typescript_client(document, options())

    assert set(files) == {
        MANIFEST,
        "core.ts",
        "namespaces/greeting.ts",
        "namespaces/index.ts",
        "client.ts",
        "errors.ts",
        "index.ts",
        "routes.ts",
        "models.ts",
    }
    assert all(
        content.startswith(
            "// Generated by fastapi-canon from greeting.openrpc.json.\n"
            "// Do not edit this file manually.\n"
            "// Regenerate it from the OpenRPC document instead.\n"
        )
        for name, content in files.items()
        if name != MANIFEST
    )


def test_renders_typed_api_groups_and_notifications(document: dict[str, Any]) -> None:
    files = render_typescript_client(document, options())
    api = files["namespaces/greeting.ts"]
    client = files["client.ts"]

    assert "export class Greeting {" in api
