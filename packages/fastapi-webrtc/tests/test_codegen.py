def test_writer_owns_its_files(tmp_path: Path) -> None:
    output = tmp_path / "client"
    assert write_files(output, {"a.ts": "a", "sub/b.ts": "b"}, check=True)
    assert not output.exists()
    changed = write_files(output, {"a.ts": "a", "sub/b.ts": "b"})
    assert len(changed) == 3
    assert json.loads((output / MANIFEST).read_text())["files"] == ["a.ts", "sub/b.ts"]
    (output / "mine.ts").write_text("kept")
    assert write_files(output, {"a.ts": "a", "sub/b.ts": "b"}, check=True) == ()
    changed = write_files(output, {"a.ts": "A"})
    assert {p.name for p in changed} == {"a.ts", "b.ts", MANIFEST}
    assert not (output / "sub/b.ts").exists()
    assert (output / "mine.ts").read_text() == "kept"
    for unsafe in ("../x.ts", "/abs.ts", "c:x.ts", "a\\b.ts", "."):
        with pytest.raises(ValueError):
            write_files(output, {unsafe: "x"})
    with pytest.raises(ValueError, match="reserved"):
        write_files(output, {MANIFEST: "x"})
    (output / MANIFEST).write_text('{"files": "nope"}')
    with pytest.raises(ValueError, match="manifest"):
        write_files(output, {"a.ts": "A"})


