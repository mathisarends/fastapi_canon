def contract() -> dict[str, Any]:
    return build_contract(contract_app.app)


def session(**overrides: Any) -> dict[str, Any]:
    value: dict[str, Any] = {
        "name": "s",
        "path": "/s",
        "role": "answerer",
        "description": None,
        "parameters": [],
        "media": {"audio": None, "video": None, "max_incoming_tracks": 4},
        "channels": [],
    }
    value.update(overrides)
    return value


def minimal(*sessions: dict[str, Any], **definitions: Any) -> dict[str, Any]:
    return {
        "contract_version": 1,
        "protocol": 1,
        "subprotocol": "fastapi-webrtc.v1",
        "sessions": list(sessions),
        "definitions": definitions,
    }


def channel(name: str = "c", **overrides: Any) -> dict[str, Any]:
    value: dict[str, Any] = {
        "name": name,
        "id": 0,
        "negotiated": True,
        "ordered": True,
        "max_retransmits": None,
        "max_packet_life_time_ms": None,
        "max_message_bytes": 65536,
        "receive_format": "json",
        "send_format": "json",
        "receive_schema": None,
        "send_schema": None,
    }
    value.update(overrides)
    return value


def test_generated_files() -> None:
    files = generate_typescript(contract(), client_name="GameClient", header="v1")
