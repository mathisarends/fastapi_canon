def test_cli_generates_clients(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    contract_file = tmp_path / "contract.json"
    contract_file.write_text(json.dumps(contract()))
    output = tmp_path / "client"
    args = ["generate", "--contract", str(contract_file), "--output", str(output)]
    assert main([*args, "--client-name", "GameClient"]) == 0
    manifest = json.loads((output / MANIFEST).read_text())
    assert manifest["generation"]["client_name"] == "GameClient"
    assert len(manifest["generation"]["contract_sha256"]) == 64
    assert main([*args, "--client-name", "GameClient", "--check"]) == 0
    assert main([*args, "--check"]) == 1
    assert "client.ts" in capsys.readouterr().err
    from_app = tmp_path / "from-app"
    assert (
        main(["generate", "--app", "tests.contract_app:app", "--output", str(from_app)])
        == 0
    )
    assert (from_app / "client.ts").read_text() == (
        output / "client.ts"
    ).read_text().replace("GameClient", "RtcClient")


