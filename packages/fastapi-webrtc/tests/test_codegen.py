    assert "  readonly seat?: number;" in client
    assert "export type ScreenShareChannels = Record<never, never>;" in client
    assert "export class GameClient {" in client
    assert "  readonly screenShare: SessionApi<" in client
    assert 'key: "gameId",' in client
    assert files["index.ts"].endswith('export * from "./client.js";\n')


