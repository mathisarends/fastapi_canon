@pytest.mark.parametrize("dependency", [False, True])
async def test_query_models_generate_working_flat_connections(
    tmp_path: Path, dependency: bool
) -> None:
    class Filters(BaseModel):
        token: str = Field(alias="access_token")
        limit: int = 10
        tags: list[str] = Field(default_factory=list)
        area: str | None = Field(default=None, validation_alias="region")

    received: list[Filters] = []
    rtc = WebRtcRouter(engine=FakeEngine())

    def filters(value: Annotated[Filters, Query()]) -> Filters:
        return value

    def session(value: Filters) -> Session:
        received.append(value)
        return Session()

    if dependency:

        def endpoint(value: Annotated[Filters, Depends(filters)]) -> Session:
            return session(value)
    else:

        def endpoint(value: Annotated[Filters, Query()]) -> Session:
            return session(value)

    rtc.session("/filters", name="filters")(endpoint)
    app = FastAPI()
    app.include_router(rtc)
    value = build_contract(app)
    parameters = value["sessions"][0]["parameters"]
    assert [(p["name"], p["required"]) for p in parameters] == [
        ("access_token", True),
        ("limit", False),
        ("tags", False),
        ("region", False),
    ]
    assert parameters[1]["schema"]["default"] == 10
    assert parameters[2]["schema"]["items"] == {"type": "string"}
    write_files(tmp_path, generate_typescript(value))
    node = shutil.which("node")
    tsc = PACKAGE / "node_modules/typescript/bin/tsc"
    assert node is not None and tsc.is_file()
    subprocess.run(
        [
            node,
            str(tsc),
            "--target",
            "ES2022",
            "--module",
            "ES2022",
            "--strict",
            "--skipLibCheck",
            "--outDir",
            str(tmp_path / "js"),
            str(tmp_path / "index.ts"),
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    (tmp_path / "js/package.json").write_text('{"type":"module"}')
    async with serve(app) as base:
        script = (
            'import { RtcClient } from "./js/index.js";\n'
            "class Socket { constructor(url) { console.log(url); throw Error(); } }\n"
            f"const client = new RtcClient({{baseUrl: {json.dumps(base)}, "
            "WebSocket: Socket, RTCPeerConnection: class {}});\n"
            'await client.filters.connect({accessToken: "valid", tags: ["a", "b"], '
            'region: "eu"})'
            ".catch(() => {});\n"
        )
        (tmp_path / "run.mjs").write_text(script)
        result = subprocess.run(
            [node, str(tmp_path / "run.mjs")],
            check=True,
            capture_output=True,
            text=True,
        )
        url = result.stdout.strip()
        assert url == f"{base}/filters?access_token=valid&tags=a&tags=b&region=eu"
        signal = await Signal.start(url)
        await signal.close()
    assert len(received) == 1
    assert received[0].model_dump() == {
        "token": "valid",
        "limit": 10,
        "tags": ["a", "b"],
        "area": "eu",
    }


@pytest.mark.parametrize(
    ("schema", "expected"),
    [
        (True, "unknown"),
        (False, "never"),
        (None, "unknown"),
        ({"const": "a"}, '"a"'),
        ({"enum": [1, "b", None]}, '1 | "b" | null'),
        ({"enum": []}, "never"),
        ({"anyOf": [{"type": "string"}, {}]}, "unknown"),
        ({"oneOf": [{"type": "integer"}, {"type": "number"}]}, "number"),
        (
            {"allOf": [{"$ref": "#/definitions/A"}, {"type": "object"}]},
            "A & Record<string, unknown>",
        ),
        ({"allOf": []}, "unknown"),
        ({"type": ["string", "null"]}, "string | null"),
        ({"type": "boolean"}, "boolean"),
        (
            {
                "type": "array",
                "items": {"anyOf": [{"type": "string"}, {"type": "null"}]},
            },
            "(string | null)[]",
        ),
        ({"type": "array"}, "unknown[]"),
        (
            {
                "type": "array",
                "prefixItems": [{"type": "string"}, {"type": "integer"}],
                "minItems": 1,
            },
            "[string, number?, ...unknown[]]",
        ),
        ({"type": "object", "additionalProperties": False}, "Record<string, never>"),
        (
            {"type": "object", "additionalProperties": {"type": "integer"}},
            "Record<string, number>",
        ),
        ({"format": "date"}, "unknown"),
    ],
)
def test_schema_translation(schema: Any, expected: str) -> None:
    contract_value = minimal(
        session(channels=[channel(send_schema=schema)]),
        A={"type": "object", "properties": {"a": {"type": "string"}}},
    )
    client = generate_typescript(contract_value)["client.ts"]
    expected = expected.replace("A &", "models.A &")
    assert f"    readonly receive: {expected};" in client


def test_object_properties_and_docs() -> None:
    schema = {
        "type": "object",
        "description": "Line one.\n\nLine three with */ inside.",
        "properties": {
            "plain": {"type": "string"},
            "needs-quotes": {"type": "integer", "description": "Quoted."},
        },
        "required": ["plain"],
        "additionalProperties": {"type": "string"},
    }
    models = generate_typescript(minimal(session(), Shape=schema))["models.ts"]
    assert "/**\n * Line one.\n *\n * Line three with *\\/ inside.\n */" in models
    assert "export interface Shape {\n  plain: string;" in models
    assert '  /** Quoted. */\n  "needs-quotes"?: number;' in models
    assert "  [key: string]: unknown;\n}" in models
    aliases = generate_typescript(
        minimal(session(), Ids={"type": "array", "items": {"type": "integer"}})
    )
    assert "export type Ids = number[];" in aliases["models.ts"]


def test_definition_names_avoid_collisions() -> None:
    files = generate_typescript(
        minimal(
            session(
                channels=[channel(send_schema={"$ref": "#/definitions/RtcSession"})]
            ),
            RtcSession={"type": "string"},
            RtcSessionModel={"type": "integer"},
            default={"type": "boolean"},
            **{"Item-Input": {"type": "string"}, "9lives": {"type": "string"}},
        )
    )
    models = files["models.ts"]
    # "RtcSession" is a runtime export, so the definition moves aside.
    assert "export type RtcSessionModel = string;" in models
    assert "export type RtcSessionModelModel = number;" in models
    assert "export type defaultModel = boolean;" in models
    assert "export type Item_Input = string;" in models
    assert "export type _9lives = string;" in models
    assert "readonly receive: models.RtcSessionModel;" in files["client.ts"]


@pytest.mark.parametrize(
    ("names", "client_name", "collision", "corrected", "corrected_client"),
    [
        (
            ["foo_bar", "fooBar"],
            "RtcClient",
            "fooBar",
            ["foo_bar", "fooBaz"],
            "RtcClient",
        ),
        (["config"], "RtcClient", "config", ["settings"], "RtcClient"),
        (["foo"], "FooSession", "FooSession", ["foo"], "FooClient"),
    ],
)
def test_generated_names_reject_collisions_before_writing(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
    names: list[str],
    client_name: str,
    collision: str,
    corrected: list[str],
    corrected_client: str,
) -> None:
    source = tmp_path / "contract.json"
    source.write_text(json.dumps(minimal(*(session(name=name) for name in names))))
    output = tmp_path / "client"
    assert (
        main(
            [
                "generate",
                "--contract",
                str(source),
                "--output",
                str(output),
                "--client-name",
                client_name,
            ]
        )
        == 2
    )
    assert collision in capsys.readouterr().err
    assert not output.exists()
    # Each reported resolution produces a real, compilable TypeScript SDK.
    write_files(
        output,
        generate_typescript(
            minimal(*(session(name=name) for name in corrected)),
            client_name=corrected_client,
        ),
    )
    node = shutil.which("node")
    tsc = PACKAGE / "node_modules/typescript/bin/tsc"
    assert node is not None and tsc.is_file()
    result = subprocess.run(
        [
            node,
            str(tsc),
            "--strict",
            "--target",
            "ES2022",
            "--module",
            "ES2022",
            "--noEmit",
            "--skipLibCheck",
            str(output / "index.ts"),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr


