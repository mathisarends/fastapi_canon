def test_generated_clients_type_check(tmp_path: Path) -> None:
    """Compile a client for every schema feature with the package's TypeScript."""
    tsc = PACKAGE / "node_modules/typescript/bin/tsc"
    node = shutil.which("node")
    if node is None or not tsc.is_file():
        pytest.skip("TypeScript is not installed (npm ci in packages/fastapi-webrtc)")
    value = copy.deepcopy(contract())
    value["definitions"]["Everything"] = {
        "type": "object",
        "properties": {
            "tuple": {
                "type": "array",
                "prefixItems": [{"type": "string"}],
                "minItems": 0,
            },
            "union": {"type": ["string", "integer", "null"]},
            "joined": {"allOf": [{"$ref": "#/definitions/Point"}, {"type": "object"}]},
            "map": {"type": "object", "additionalProperties": False},
            "quoted-key": {"enum": ["a", 1, True]},
        },
        "required": ["tuple"],
        "additionalProperties": {"type": "string"},
    }
    value["sessions"][1]["channels"] = [
        channel("everything", send_schema={"$ref": "#/definitions/Everything"})
    ]
    write_files(tmp_path / "client", generate_typescript(value))
    usage = tmp_path / "usage.ts"
    usage.write_text(
        'import { RtcClient } from "./client/index.js";\n'
        "const client = new RtcClient({ baseUrl: 'https://example.test' });\n"
        "export async function play(): Promise<void> {\n"
        "  const shared = new RtcClient({ query: async () => ({ token: 'fresh' }) });\n"
        "  await shared.game.connect({ gameId: 'g' });\n"
        "  await client.game.connect({ gameId: 'g', query: { token: 'local' } });\n"
        "  // @ts-expect-error: shared credentials cannot supply a path parameter.\n"
        "  await shared.game.connect({});\n"
        "  const game = await client.game.connect({\n"
        "    gameId: 'g', token: 't', seat: 1,\n"
        "    onMessage: { moves: (state) => void state.pieces['king']?.x },\n"
        "  });\n"
        "  await game.channels.moves.send({ to: { x: 1, y: 2 } });\n"
        "  await game.channels.moves.send({ kind: 'chat', text: 'hi' });\n"
        "  await game.channels.blob.send(new Uint8Array([1]));\n"
        "  await game.close();\n"
        "  const screen = await client.screenShare.connect({\n"
        "    onMessage: { everything: (value) => void value.tuple },\n"
        "  });\n"
        "  await screen.close();\n"
        "}\n",
        encoding="utf-8",
    )
